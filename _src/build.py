#!/usr/bin/env python3
"""Static site generator for the BudgetBear companion website.

Run `python3 _src/build.py --help` for usage. One command does the whole build: it validates the content
(_src/content/<lang>.json against _src/schema/content.schema.json), copies the App Store badges and converts the
screenshots into the language folders (see badges.py and screenshots.py), and then writes the HTML pages
(_src/templates/ and _src/blocks.py) to the repo root (default language) and <lang>/ folders.
Python 3 standard library only.
"""
import argparse, json, os, re, sys
from pathlib import Path
from types import SimpleNamespace

sys.dont_write_bytecode = True      # no __pycache__ folders in the repo
import badges, screenshots, verify
import blocks as B
from validate import Validator, load_json, structure_problems

SRC = Path(__file__).resolve().parent
ROOT = SRC.parent
CFG = json.loads((SRC / "config.json").read_text(encoding="utf-8"))
BASE, DEFAULT = CFG["base_url"], CFG["default_language"]
PAGES = CFG["pages"]
LANG_CFG = {l["code"]: l for l in CFG["languages"]}      # code = language tag (html lang, hreflang, content file name)
ALL = list(LANG_CFG)
LANGS = [c for c in ALL if c == DEFAULT or (SRC / "content" / f"{c}.json").exists()]   # languages that have content
PENDING = [c for c in ALL if c not in LANGS]
RESERVED = {"images", "styles", "_src", ".git"} | set(CFG.get("redirect_folders", [])) | set(PAGES)
BANNER = "<!-- Generated by _src/build.py from _src/content. Do not edit this file directly. -->"


def render(text, ctx, where):
    """Replace {{token}} placeholders; a token alone on a line may expand to several lines."""
    def sub(line):
        def one(m):
            if m.group(1) not in ctx:
                sys.exit(f"error: unknown token {{{{{m.group(1)}}}}} in {where}")
            return ctx[m.group(1)]
        return re.sub(r"\{\{(\w+)\}\}", one, line)
    out = []
    for line in text.split("\n"):
        m = re.fullmatch(r"(\s*)\{\{(\w+)\}\}\s*", line)
        if m and "\n" in ctx.get(m.group(2), ""):
            out += [(m.group(1) + l) if l else l for l in sub("{{%s}}" % m.group(2)).split("\n")]
        else:
            out.append(sub(line))
    return "\n".join(out)


def lang_dir(lang):                  # folder name: URL folder and folder of the language's images; defaults to the code
    return LANG_CFG[lang].get("dir", lang)


def page_dir(lang):
    return "" if lang == DEFAULT else lang_dir(lang) + "/"


def config_problems():
    out, dirs = [], {}
    if DEFAULT not in LANG_CFG:
        out.append(f'config.json: default_language "{DEFAULT}" is not in languages')
    for code in ALL:
        d = lang_dir(code)
        if not re.fullmatch(r"[a-z0-9-]+", d):
            out.append(f'config.json: folder "{d}" of language {code} must be lowercase letters, digits and hyphens')
        if d in RESERVED:
            out.append(f'config.json: folder "{d}" of language {code} is reserved')
        if d in dirs:
            out.append(f'config.json: languages {dirs[d]} and {code} share the folder "{d}"')
        dirs[d] = code
    if len(ALL) != len(CFG["languages"]):
        out.append("config.json: duplicate language code")
    for loc, code in CFG.get("app_store_locales", {}).items():
        if code not in LANG_CFG:
            out.append(f'config.json: app_store_locales {loc} points to unknown language "{code}"')
    return out


def page_path(lang, page):          # path relative to the site root, as in the URL
    return page_dir(lang) + ("" if page == "index" else page)


def load_and_validate(langs):
    """Load content for `langs` (plus the default language as reference); return (data, errors)."""
    schema = json.loads((SRC / "schema" / "content.schema.json").read_text(encoding="utf-8"))
    data, errors = {}, config_problems()
    for lg in dict.fromkeys([DEFAULT] + langs):
        f = SRC / "content" / f"{lg}.json"
        d, e = load_json(f)
        if e:
            errors.append(e)
            continue
        v = Validator(schema)
        v.check(d, schema)
        errors += [f"{lg}: {m}" for m in v.errors]
        data[lg] = d
    if DEFAULT in data and not errors:
        for lg in langs:
            if lg != DEFAULT:
                errors += structure_problems(lg, data[lg], DEFAULT, data[DEFAULT])
    return data, errors


def build_page(lang, page, tpl, langs_data):
    L = langs_data[lang]
    P = L["pages"][page]
    depth = 0 if lang == DEFAULT else 1
    root = "../" * depth
    site_url = BASE + page_dir(lang)
    own_badge = ROOT / page_dir(lang) / "images" / L["badge_file"]      # the language's own images folder, else the root one
    badge_src = ("images/" if own_badge.exists() else root + "images/") + L["badge_file"]
    bctx = B.Ctx(root, site_url, badge_src, L["badge_alt"], CFG["app_store_url"], CFG["contact"], L["contact"])
    body = B.render_blocks(P["blocks"], bctx)

    url = lambda lg: BASE + page_path(lg, page)
    hreflang = "\n".join(f'<link rel="alternate" hreflang="{lg}" href="{url(lg)}">' for lg in LANGS)
    hreflang += f'\n<link rel="alternate" hreflang="x-default" href="{url(DEFAULT)}">'

    nav = L["nav"]
    footer = []
    for key, href, name in [("home", "./", "index"), ("privacy", "privacy", "privacy"), ("contact", "contact", "contact")]:
        cls = ' class="active"' if page == name else ""
        footer.append(f'<a href="{href}"{cls}>{B.esc_text(nav[key])}</a>')

    options = []
    for lg in LANGS:
        name = B.esc_text(langs_data[lg]["name"])
        if lg == lang:
            options.append(f'<span class="language-option active current">{name}</span>')
        else:
            href = "../" * depth + page_path(lg, page)
            options.append(f'<a href="{href or "./"}" hreflang="{lg}" class="language-option">{name}</a>')

    extra = ""
    if page == "index":
        ld = {"@context": "https://schema.org", "@type": "SoftwareApplication", "name": "BudgetBear",
              "operatingSystem": "iOS, iPadOS, macOS", "applicationCategory": "FinanceApplication",
              "offers": {"@type": "Offer", "price": "0", "priceCurrency": L["currency"]},
              "description": P["description"]}
        j = json.dumps(ld, indent=4, ensure_ascii=False).replace("</", "<\\/")
        extra = '<script type="application/ld+json">\n' + j + "\n</script>"

    ctx = {
        "lang": lang, "root": root, "banner": BANNER,
        "title": B.esc_text(P["title"]), "og_title": B.esc_attr(P["og_title"]),
        "description": B.esc_attr(P["description"]), "og_description": B.esc_attr(P["og_description"]),
        "keywords": B.esc_attr(P["keywords"]), "page_url": url(lang),
        "hreflang_links": hreflang, "structured_data": extra,
        "tagline": B.esc_text(L["tagline"]), "icon_alt": B.esc_attr(L["icon_alt"]),
        "footer_links": "\n".join(footer), "current_language": B.esc_text(L["name"]),
        "language_options": "\n".join(options), "copyright": B.esc_text(L["copyright"]),
        "content": body,
    }
    out = render(tpl, ctx, "templates/page.html")
    out = re.sub(r"[ \t]+\n", "\n", out)                    # no trailing whitespace
    out = re.sub(r"\n{3,}", "\n\n", out)                    # at most one blank line
    return re.sub(r"\n\n(\s*</head>)", r"\n\1", out)        # no blank line before </head>


def parse_args():
    ap = argparse.ArgumentParser(
        prog="python3 _src/build.py",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        description="Build the website: validate the content, copy the App Store badges, convert the screenshots and\n"
                    "generate the pages. Only languages that have a content file are built.",
        epilog="examples:\n"
               "  python3 _src/build.py                 the whole build (the usual command)\n"
               "  python3 _src/build.py --build-only    only validate and generate the pages, leave badges and screenshots alone\n"
               "  python3 _src/build.py --validate      validate the content only\n"
               "  python3 _src/build.py -c              show what a build would change, write nothing\n"
               "  python3 _src/build.py --verify        the final check before uploading (read-only)\n"
               "  python3 _src/build.py --lang de       build German only\n\n"
               "input:  _src/config.json, _src/content/<lang>.json, _src/schema/content.schema.json, _src/templates/,\n"
               "        the badge download (_src/badges.json) and the fastlane screenshots (_src/screenshots.json)\n"
               "output: HTML pages and <language folder>/images/; never edit the generated files by hand.\n"
               "format: see _src/README.md")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--validate", action="store_true", help="validate the content only, write nothing")
    mode.add_argument("-c", "--check", action="store_true",
                      help="show what a build would change (badges, screenshots, pages); write nothing, exit code 1 if anything is to do")
    mode.add_argument("--verify", action="store_true",
                      help="final check before uploading: are all pages, badges, screenshots, links and switchers complete and correct? "
                           "Read-only; exit code 1 if anything is wrong")
    ap.add_argument("--build-only", action="store_true", help="skip the badges and screenshots, only validate and generate the pages")
    ap.add_argument("--force", action="store_true", help="copy the badges and convert the screenshots again even if they are up to date")
    ap.add_argument("--lang", action="append", default=[], metavar="LANG",
                    help="restrict the build to this language (repeatable); "
                         "the default language is always read for the structure comparison")
    return ap.parse_args()


def make_outputs(langs, data, only_selected):
    """All generated files as {path: html}, in memory."""
    tpl = (SRC / "templates" / "page.html").read_text(encoding="utf-8")
    redir = (SRC / "templates" / "redirect.html").read_text(encoding="utf-8")
    outputs = {}
    for lg in langs:
        for page in PAGES:
            outputs[ROOT / (page_dir(lg) + page + ".html")] = build_page(lg, page, tpl, data)
    if not only_selected:
        for folder in CFG.get("redirect_folders", []):      # legacy URLs, e.g. /gb/
            for page in PAGES:
                target = BASE + page_path(DEFAULT, page)
                outputs[ROOT / folder / (page + ".html")] = render(redir, {"url": target}, "templates/redirect.html")
    return outputs


def main():
    args = parse_args()
    validate_only, check, only = args.validate, args.check, args.lang
    unknown = [l for l in only if l not in ALL]
    if unknown:
        sys.exit(f"error: language {', '.join(unknown)} is not in config.json (languages: {', '.join(ALL)})")
    nocontent = [l for l in only if l in PENDING]
    if nocontent:
        sys.exit(f"error: no content yet for {', '.join(nocontent)}; create _src/content/{nocontent[0]}.json first")
    langs = only or LANGS

    data, errors = load_and_validate(langs)
    if errors:
        print(f"{len(errors)} problem(s) in the content:")
        for e in errors[:60]:
            print("  -", e)
        if len(errors) > 60:
            print(f"  ... and {len(errors) - 60} more")
        sys.exit(1)
    for lg in LANGS:                  # switcher and hreflang need every active language's name, validated or not
        if lg not in data:
            d, _ = load_json(SRC / "content" / f"{lg}.json")
            data[lg] = d if d and "name" in d else {"name": lg}

    pending = f"\npending languages (no content file yet): {', '.join(PENDING)}" if PENDING and not only else ""
    if validate_only:
        print(f"content valid: {', '.join(langs)}{pending}")
        return
    if args.verify:
        outputs = make_outputs(langs, data, bool(only))
        sys.exit(verify.run(SimpleNamespace(root=ROOT, base=BASE, default=DEFAULT, active=LANGS, pending=PENDING, langs=langs, data=data,
                                            outputs=outputs, page_dir=page_dir, page_path=page_path, cfg=CFG, all_langs=not only)))
    print(f"content:     valid ({', '.join(langs)})")

    todo = 0                                  # things a build would still change (for --check)
    asset_problems = 0
    if not args.build_only:                   # badges and screenshots come first: the pages link to what exists
        for label, step, verb, past in (("badges", badges, "copy", "copied"), ("screenshots", screenshots, "convert", "converted")):
            r = step.sync(langs, force=args.force, dry_run=check)
            if r["unavailable"]:
                print(f"{label + ':':12} skipped, {r['unavailable']}")
                continue
            done = f"{len(r['changes'])} to {verb}" if check else f"{len(r['changes'])} {past}"
            print(f"{label + ':':12} {done}, {r['skipped']} up to date" + (f", {len(r['problems'])} problem(s)" if r["problems"] else ""))
            if check:
                for c in r["changes"]:
                    print("             would " + verb + " " + c)
            for pr in r["problems"]:
                print("warning:", pr)
            todo += len(r["changes"]) if check else 0
            asset_problems += len(r["problems"])

    outputs = make_outputs(langs, data, bool(only))

    stale, problems = [], []
    for path, html in outputs.items():
        for ref in re.findall(r'(?:src|href)="((?!https?:|mailto:|tel:|#)[^"]+\.(?:webp|svg|png|ico|css))"', html):
            if not Path(os.path.normpath(path.parent / ref)).exists():
                problems.append(f"{path.relative_to(ROOT)}: missing asset {ref}")
        if not path.exists() or path.read_text(encoding="utf-8") != html:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(html, encoding="utf-8")
    for p in problems:
        print("warning:", p)
    verb = "out of date" if check else "written"
    print(f"{'pages:':12} {len(outputs)} pages, {len(stale)} {verb}" + ("" if not stale else ": " + ", ".join(str(p.relative_to(ROOT)) for p in stale)) + pending)
    if (check and (stale or todo)) or asset_problems:
        sys.exit(1)


if __name__ == "__main__":
    main()
