#!/usr/bin/env python3
"""Static site generator for the BudgetBear companion website.

Usage (from the repo root):
    python3 _src/build.py           # (re)generate all pages
    python3 _src/build.py --check   # report pages that are out of date, change nothing

Sources live in _src/ (config.json, templates/, content/<lang>/). The generated
HTML files are written to the repo root (en) and <lang>/ folders and must not be
edited by hand. Python 3 standard library only.
"""
import json, os, re, sys
from pathlib import Path

SRC = Path(__file__).resolve().parent
ROOT = SRC.parent
CFG = json.loads((SRC / "config.json").read_text(encoding="utf-8"))
BASE, DEFAULT = CFG["base_url"], CFG["default_language"]
LANGS, PAGES = CFG["languages"], CFG["pages"]
META_KEYS = ["title", "og_title", "description", "og_description", "keywords"]
BANNER = "<!-- Generated by _src/build.py from _src/content. Do not edit this file directly. -->"


def esc_text(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def esc_attr(s):
    return esc_text(s).replace('"', "&quot;")


def render(text, ctx, where):
    """Replace {{token}} placeholders; a token alone on a line may expand to several lines."""
    def sub(line):
        def one(m):
            if m.group(1) not in ctx:
                sys.exit(f"error: unknown token {{{{{m.group(1)}}}}} in {where}")
            return ctx[m.group(1)]
        return re.sub(r"\{\{(\w+)\}\}", one, line)
    out = []
    for line in text.split("\n"):
        m = re.fullmatch(r"(\s*)\{\{(\w+)\}\}\s*", line)
        if m and "\n" in ctx.get(m.group(2), ""):
            out += [(m.group(1) + l) if l else l for l in sub("{{%s}}" % m.group(2)).split("\n")]
        else:
            out.append(sub(line))
    return "\n".join(out)


def page_dir(lang):
    return "" if lang == DEFAULT else lang + "/"


def page_path(lang, page):          # path relative to the site root, as in the URL
    return page_dir(lang) + ("" if page == "index" else page)


def load_page(lang, page):
    f = SRC / "content" / lang / f"{page}.html"
    text = f.read_text(encoding="utf-8")
    m = re.match(r"<!--\n(.*?)\n-->\n", text, re.S)
    if not m:
        sys.exit(f"error: {f.relative_to(ROOT)} must start with a <!-- ... --> metadata block")
    meta = {}
    for line in m.group(1).split("\n"):
        k, _, v = line.partition(": ")
        meta[k.strip()] = v.strip()
    missing = [k for k in META_KEYS if not meta.get(k)]
    if missing:
        sys.exit(f"error: {f.relative_to(ROOT)} lacks metadata: {', '.join(missing)}")
    return meta, text[m.end():].strip("\n")


def build_page(lang, page, tpl, langs_data):
    L = langs_data[lang]
    meta, body = load_page(lang, page)
    depth = 0 if lang == DEFAULT else 1
    root = "../" * depth
    badge = (f'<a href="{CFG["app_store_url"]}" target="_blank" rel="noopener">\n'
             f'    <img src="{root}images/badges/{L["badge_file"]}" alt="{esc_attr(L["badge_alt"])}" class="download-cta-badge">\n'
             f'</a>')
    body = render(body, {"root": root, "lang": lang, "app_store_badge": badge}, f"content/{lang}/{page}.html")

    url = lambda lg: BASE + page_path(lg, page)
    hreflang = "\n".join(f'<link rel="alternate" hreflang="{lg}" href="{url(lg)}">' for lg in LANGS)
    hreflang += f'\n<link rel="alternate" hreflang="x-default" href="{url(DEFAULT)}">'

    nav = L["nav"]
    footer = []
    for key, href, name in [("home", "./", "index"), ("privacy", "privacy", "privacy"), ("contact", "contact", "contact")]:
        cls = ' class="active"' if page == name else ""
        footer.append(f'<a href="{href}"{cls}>{esc_text(nav[key])}</a>')

    options = []
    for lg in LANGS:
        name = esc_text(langs_data[lg]["name"])
        if lg == lang:
            options.append(f'<span class="language-option active current">{name}</span>')
        else:
            href = "../" * depth + page_path(lg, page)
            options.append(f'<a href="{href or "./"}" hreflang="{lg}" class="language-option">{name}</a>')

    extra = ""
    if page == "index":
        ld = {"@context": "https://schema.org", "@type": "SoftwareApplication", "name": "BudgetBear",
              "operatingSystem": "iOS, iPadOS, macOS", "applicationCategory": "FinanceApplication",
              "offers": {"@type": "Offer", "price": "0", "priceCurrency": L["currency"]},
              "description": meta["description"]}
        j = json.dumps(ld, indent=4, ensure_ascii=False).replace("</", "<\\/")
        extra = '<script type="application/ld+json">\n' + j + "\n</script>"

    ctx = {
        "lang": lang, "root": root, "banner": BANNER,
        "title": esc_text(meta["title"]), "og_title": esc_attr(meta["og_title"]),
        "description": esc_attr(meta["description"]), "og_description": esc_attr(meta["og_description"]),
        "keywords": esc_attr(meta["keywords"]), "page_url": url(lang),
        "hreflang_links": hreflang, "structured_data": extra,
        "tagline": esc_text(L["tagline"]), "icon_alt": esc_attr(L["icon_alt"]),
        "footer_links": "\n".join(footer), "current_language": esc_text(L["name"]),
        "language_options": "\n".join(options), "copyright": esc_text(L["copyright"]),
        "content": body,
    }
    out = render(tpl, ctx, "templates/page.html")
    out = re.sub(r"[ \t]+\n", "\n", out)                    # no trailing whitespace
    out = re.sub(r"\n{3,}", "\n\n", out)                    # at most one blank line
    return re.sub(r"\n\n(\s*</head>)", r"\n\1", out)      # no blank line before </head>


def main():
    check = "--check" in sys.argv
    tpl = (SRC / "templates" / "page.html").read_text(encoding="utf-8")
    redir = (SRC / "templates" / "redirect.html").read_text(encoding="utf-8")
    langs_data = {lg: json.loads((SRC / "content" / lg / "lang.json").read_text(encoding="utf-8")) for lg in LANGS}

    outputs = {}
    for lg in LANGS:
        for page in PAGES:
            outputs[ROOT / (page_dir(lg) + page + ".html")] = build_page(lg, page, tpl, langs_data)
    for folder in CFG.get("redirect_folders", []):      # legacy URLs, e.g. /gb/
        for page in PAGES:
            target = BASE + page_path(DEFAULT, page)
            outputs[ROOT / folder / (page + ".html")] = render(redir, {"url": target}, "templates/redirect.html")

    stale, problems = [], []
    for path, html in outputs.items():
        for ref in re.findall(r'(?:src|href)="((?!https?:|mailto:|tel:|#)[^"]+\.(?:webp|svg|png|ico|css))"', html):
            if not Path(os.path.normpath(path.parent / ref)).exists():
                problems.append(f"{path.relative_to(ROOT)}: missing asset {ref}")
        if not path.exists() or path.read_text(encoding="utf-8") != html:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(html, encoding="utf-8")
    for p in problems:
        print("warning:", p)
    verb = "out of date" if check else "written"
    print(f"{len(outputs)} pages, {len(stale)} {verb}" + ("" if not stale else ": " + ", ".join(str(p.relative_to(ROOT)) for p in stale)))
    if check and stale:
        sys.exit(1)


if __name__ == "__main__":
    main()
